"""
Worker Service — Windows Scheduled Task manager for control_plane.worker.

Subcommands:
    register      Create/replace the scheduled task (idempotent)
    unregister    Remove the scheduled task
    status        Show task state, last run, next run, and live process info
    start         schtasks /Run — start the task immediately
    stop          schtasks /End — stop the running task
    logs          Tail the launcher log
    reinstall     unregister + register (use after editing launcher.ps1)

Task properties:
    Name      : 'Camelot Worker'
    Trigger   : ONLOGON  (also runs immediately on register if --start passed)
    Account   : current user (no admin needed)
    Action    : powershell.exe -File bin/worker_launcher.ps1
    Restart   : built into the launcher loop (10s backoff on crash)

The launcher (bin/worker_launcher.ps1) is generated on first register if it
does not exist. Edit it directly to customize the restart policy, then run
'reinstall'.
"""
from __future__ import annotations

import argparse
import os
import platform
import subprocess
import sys
import time
from pathlib import Path

HOME = Path(__file__).resolve().parent.parent
LAUNCHER_PS1 = HOME / "bin" / "worker_launcher.ps1"
LAUNCHER_LOG = HOME / "logs" / "worker_service.log"
LAUNCHER_PID = HOME / "logs" / "worker_service.pid"
TASK_NAME = "Camelot Worker"

LAUNCHER_TEMPLATE = r"""# Camelot Worker launcher — invoked by Windows Scheduled Task 'Camelot Worker'.
# Auto-generated by bin/worker_service.py. Safe to edit; run 'worker_service.py reinstall' after changes.
$ErrorActionPreference = "Continue"
$Home_ = "{HOME}"
$Python = Join-Path $Home_ ".venv\Scripts\python.exe"
$Log = Join-Path $Home_ "logs\worker_service.log"
$PidFile = Join-Path $Home_ "logs\worker_service.pid"
$env:CAMELOT_OS_HOME = $Home_
Set-Location $Home_
$PID | Out-File -FilePath $PidFile -Encoding ascii -Force
function Log($msg) {{
    $ts = (Get-Date).ToString("yyyy-MM-dd HH:mm:ss")
    "[$ts] [LAUNCHER] $msg" | Out-File -FilePath $Log -Append -Encoding utf8
}}
Log "Launcher started; python=$Python"
while ($true) {{
    try {{
        Log "Spawning worker..."
        & $Python -m control_plane.worker --auto-approve *>> $Log
        $code = $LASTEXITCODE
        Log "Worker exited with code $code; restarting in 10s"
    }} catch {{
        Log "Worker threw: $_; restarting in 10s"
    }}
    Start-Sleep -Seconds 10
}}
"""


def _require_windows() -> None:
    if platform.system() != "Windows":
        print("ERROR: worker_service is Windows-only (uses schtasks)", file=sys.stderr)
        sys.exit(2)


def _ensure_launcher() -> None:
    if LAUNCHER_PS1.exists():
        return
    LAUNCHER_PS1.parent.mkdir(parents=True, exist_ok=True)
    content = LAUNCHER_TEMPLATE.format(HOME=str(HOME))
    LAUNCHER_PS1.write_text(content, encoding="utf-8")
    print(f"[OK] Wrote launcher: {LAUNCHER_PS1}")


def _task_exists() -> bool:
    r = subprocess.run(
        ["schtasks", "/Query", "/TN", TASK_NAME],
        capture_output=True, text=True,
    )
    return r.returncode == 0


def _run_schtasks(args: list[str], check: bool = True) -> subprocess.CompletedProcess:
    r = subprocess.run(["schtasks"] + args, capture_output=True, text=True)
    if check and r.returncode != 0:
        print(f"[FAIL] schtasks {' '.join(args)}", file=sys.stderr)
        print(r.stdout, file=sys.stderr)
        print(r.stderr, file=sys.stderr)
        sys.exit(r.returncode)
    return r


def cmd_register(args: argparse.Namespace) -> int:
    _require_windows()
    _ensure_launcher()
    if _task_exists():
        print(f"[..] Task '{TASK_NAME}' already exists — replacing")
        _run_schtasks(["/Delete", "/TN", TASK_NAME, "/F"])
    powershell = r"C:\Windows\System32\WindowsPowerShell\v1.0\powershell.exe"
    cmd_str = f'"{powershell}" -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "{LAUNCHER_PS1}"'
    _run_schtasks([
        "/Create",
        "/TN", TASK_NAME,
        "/TR", cmd_str,
        "/SC", "ONLOGON",
        "/RL", "LIMITED",
        "/F",
    ])
    print(f"[OK] Registered scheduled task '{TASK_NAME}' (trigger: ONLOGON)")
    if args.start:
        return cmd_start(args)
    print(f"[..] Run '{Path(__file__).name} start' to launch now, or log out/in to auto-start")
    return 0


def cmd_unregister(args: argparse.Namespace) -> int:
    _require_windows()
    if not _task_exists():
        print(f"[..] Task '{TASK_NAME}' not registered — nothing to do")
        return 0
    _run_schtasks(["/Delete", "/TN", TASK_NAME, "/F"])
    print(f"[OK] Unregistered scheduled task '{TASK_NAME}'")
    return 0


def cmd_status(args: argparse.Namespace) -> int:
    _require_windows()
    if not _task_exists():
        print(f"[--] Task '{TASK_NAME}' NOT registered")
        return 1
    r = _run_schtasks(["/Query", "/TN", TASK_NAME, "/V", "/FO", "LIST"], check=False)
    interesting = ("Status:", "Last Run Time:", "Last Result:", "Next Run Time:", "Run As User:")
    for line in r.stdout.splitlines():
        if any(line.strip().startswith(k) for k in interesting):
            print(f"  {line.strip()}")
    if LAUNCHER_PID.exists():
        pid = LAUNCHER_PID.read_text(encoding="ascii", errors="ignore").strip()
        print(f"  Launcher PID file: {pid}")
        alive = subprocess.run(
            ["tasklist", "/FI", f"PID eq {pid}"],
            capture_output=True, text=True,
        )
        if pid and pid in alive.stdout:
            print(f"  Launcher process: ALIVE (pid {pid})")
        else:
            print(f"  Launcher process: not running (stale pid file)")
    else:
        print("  Launcher PID file: absent")
    if LAUNCHER_LOG.exists():
        size = LAUNCHER_LOG.stat().st_size
        mtime = time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(LAUNCHER_LOG.stat().st_mtime))
        print(f"  Launcher log: {LAUNCHER_LOG} ({size:,} bytes, last write {mtime})")
    return 0


def cmd_start(args: argparse.Namespace) -> int:
    _require_windows()
    if not _task_exists():
        print(f"[FAIL] Task '{TASK_NAME}' not registered — run 'register' first", file=sys.stderr)
        return 1
    _run_schtasks(["/Run", "/TN", TASK_NAME])
    print(f"[OK] Started task '{TASK_NAME}'")
    return 0


def cmd_stop(args: argparse.Namespace) -> int:
    _require_windows()
    if not _task_exists():
        print(f"[..] Task '{TASK_NAME}' not registered")
        return 0
    _run_schtasks(["/End", "/TN", TASK_NAME], check=False)
    print(f"[OK] Stop signal sent to task '{TASK_NAME}'")
    return 0


def cmd_logs(args: argparse.Namespace) -> int:
    if not LAUNCHER_LOG.exists():
        print(f"[..] No launcher log at {LAUNCHER_LOG}")
        return 0
    n = args.lines
    lines = LAUNCHER_LOG.read_text(encoding="utf-8", errors="replace").splitlines()
    for line in lines[-n:]:
        print(line)
    return 0


def cmd_reinstall(args: argparse.Namespace) -> int:
    cmd_unregister(args)
    return cmd_register(args)


def main() -> int:
    p = argparse.ArgumentParser(description="Manage the Camelot worker as a Windows scheduled task")
    sub = p.add_subparsers(dest="cmd", required=True)
    pr = sub.add_parser("register", help="Create/replace the scheduled task")
    pr.add_argument("--start", action="store_true", help="Also start it immediately after register")
    pr.set_defaults(func=cmd_register)
    sub.add_parser("unregister", help="Remove the scheduled task").set_defaults(func=cmd_unregister)
    sub.add_parser("status", help="Show task and process status").set_defaults(func=cmd_status)
    sub.add_parser("start", help="Run the task now").set_defaults(func=cmd_start)
    sub.add_parser("stop", help="Stop the running task").set_defaults(func=cmd_stop)
    pl = sub.add_parser("logs", help="Tail the launcher log")
    pl.add_argument("-n", "--lines", type=int, default=40, help="Number of lines (default 40)")
    pl.set_defaults(func=cmd_logs)
    pri = sub.add_parser("reinstall", help="unregister + register")
    pri.add_argument("--start", action="store_true")
    pri.set_defaults(func=cmd_reinstall)
    args = p.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
