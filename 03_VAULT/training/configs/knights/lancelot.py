    def _dependency_map(self, target_path: str) -> dict:
        lines = [f"[LANCELOT] Dependency Map: `{target_path}`", ""]

        try:
            abs_path = Path(target_path).expanduser().resolve()
            if abs_path.exists() and abs_path.suffix == ".py":
                source = abs_path.read_text(encoding="utf-8", errors="replace")
                tree = ast.parse(source)

                imports = []
                for node in ast.walk(tree):
                    if isinstance(node, ast.Import):
                        for alias in node.names:
                            imports.append(("import", alias.name, alias.asname))
                    elif isinstance(node, ast.ImportFrom):
                        module = node.module or ""
                        for alias in node.names:
                            imports.append(("from", f"{module}.{alias.name}", alias.asname))

                stdlib = []
                local = []
                third_party = []

                for kind, name, alias in imports:
                    top = name.split(".")[0]
                    if top.startswith(".") or top in ("knights", "control_plane", "squires", "ouroboros"):
                        local.append((kind, name, alias))
                    else:
                        # Simple heuristic: common stdlib modules
                        _STDLIB = {"os", "sys", "re", "ast", "json", "time", "pathlib",
                                   "typing", "abc", "subprocess", "shutil", "hashlib",
                                   "collections", "functools", "itertools", "dataclasses",
                                   "logging", "datetime", "math", "io", "contextlib"}
                        if top in _STDLIB:
                            stdlib.append((kind, name, alias))
                        else:
                            third_party.append((kind, name, alias))

                def _fmt(entries):
                    out = []
                    for kind, name, alias in entries:
                        s = f"  {kind} {name}"
                        if alias:
                            s += f" as {alias}"
                        out.append(s)
                    return "\n".join(out) if out else "  (none)"

                lines.append("### Standard Library")
                lines.append(_fmt(stdlib))
                lines.append("")
                lines.append("### Third-Party")
                lines.append(_fmt(third_party))
                lines.append("")
                lines.append("### Internal (Camelot)")
                lines.append(_fmt(local))
                lines.append("")
                lines.append(f"**Total imports: {len(imports)}** "
                           f"(stdlib: {len(stdlib)}, 3rd-party: {len(third_party)}, internal: {len(local)})")
            else:
                lines.append(f"File not found or not Python: `{target_path}`")
        except Exception as e:
            lines.append(f"[ERROR] {e}")

        return {"status": "success", "output": "\n".join(lines), "files_created": []}

