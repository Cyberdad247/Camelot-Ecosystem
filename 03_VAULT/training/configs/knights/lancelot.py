        output += "- Dependencies must be explicit (no dynamic imports in public API)\n"
        output += "- Invariants are tested in module-level assertions or unit tests\n"
        output += "- Breaking changes require ADR (route to Sir Synthesis)\n"

        return {"status": "success", "output": output, "files_created": []}

