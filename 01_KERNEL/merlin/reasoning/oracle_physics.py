import random
from typing import Any, Dict

from kernel.agora.context import SovereignContext
from kernel.agora.models.proteus_vector import ProteusVector


class OraclePhysics:
    """
    The Physics Engine of the Simulation Hypervisor.
    Manages Time, Causality, and Chaos (LaC).
    """

    def __init__(self):
        self.lac_active = False

    def lac_walk(self, base_temp: float = 0.8) -> float:
        """
        Learning-at-Criticality (LaC) Random Walk.
        Oscillates temperature to inject 'Black Swan' events.
        """
        if not self.lac_active:
            return base_temp

        # Chaos Coefficient: 0.8 -> 1.2
        chaos = random.uniform(-0.2, 0.2)
        return max(0.1, min(1.5, base_temp + chaos))

    def step(self, context: SovereignContext) -> SovereignContext:
        """
        Advances the simulation by 1 Epoch.
        Calculates Global Tension and Resource Decay.
        """
        state = context.world_state
        state["epoch"] += 1

        # Entropy: Resources decay over time
        # This is a placeholder for more complex logic
        # In a real system, this would interact with the LLM to determine decay

        # Tension Oscillation (LaC)
        current_tension = state.get("global_tension", 0.5)
        new_tension = self.lac_walk(current_tension)
        state["global_tension"] = round(new_tension, 2)

        return context

    def tree_of_thoughts(self, actor: ProteusVector, goal: str) -> Dict[str, Any]:
        """
        Simulates 3 potential futures for an actor's move.
        Selects the path with the highest Utility Score.
        """
        # 1. Decompose (Simulated Paths)
        # In a real system, these would be generated by the LLM
        path_a_risk = 0.2
        path_b_risk = 0.5
        path_c_risk = 0.9

        paths = [
            {"id": "A", "desc": "Conservative Approach", "risk": path_a_risk},
            {"id": "B", "desc": "Balanced Approach", "risk": path_b_risk},
            {"id": "C", "desc": "Radical/Betrayal Approach", "risk": path_c_risk},
        ]

        # 2. Score Utility based on Actor's Vector
        best_path = None
        highest_utility = -999.0

        for path in paths:
            score = actor.utility_score(path["risk"])
            path["utility"] = score

            # Check for betrayal threshold if risk is high
            if path["risk"] > 0.7:
                if not actor.would_betray(path["risk"]):
                    path["desc"] += " [BLOCKED BY LOYALTY]"
                    score = -1.0  # Penalize blocked paths

            if score > highest_utility:
                highest_utility = score
                best_path = path

        # 3. Commit
        return {
            "selected_path": best_path,
            "all_paths": paths,
            "reasoning": f"Chosen {best_path['id']} (Utility: {highest_utility:.2f}) based on Agency: {actor.agency} / Morality: {actor.morality}",
        }


# Singleton
physics = OraclePhysics()