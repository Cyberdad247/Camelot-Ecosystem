# -------------------------------------------------------------- phial_main
def phial_main(raw_input: str) -> dict:
    """Standard Phial entrypoint — JSON in {action, seed}, dict out."""
    try:
        payload = json.loads(raw_input) if raw_input.strip().startswith("{") else {"action": "cycle", "seed": raw_input}
    except json.JSONDecodeError:
        payload = {"action": "cycle", "seed": raw_input}
    action = str(payload.get("action", "cycle")).lower()
    seed = str(payload.get("seed", "default research cycle"))
    engine = PhialEngine()
    try:
        if action == "forge":
            return engine.forge_scaffold()
        if action == "sync":
            return engine.sync_vfs()
        if action == "state":
            return {"status": "OK", "state": engine.state()}
        if action == "reset":
            return engine.reset()
        if action == "deploy":
            return engine.deploy_artifact(seed)
        return engine.run_cycle(seed)  # cycle (default)
    except Exception as e:
        return {"status": "ERROR", "action": action, "message": str(e)}


def _self_test() -> int:
    """Side-effect-free self-check: runs entirely in a temp workspace."""
    import tempfile

    ok = True

    def check(name: str, cond: bool, detail: str = "") -> None:
        nonlocal ok
        mark = "PASS" if cond else "FAIL"
        if not cond:
            ok = False
        print(f"[{mark}] {name} {detail}")

    with tempfile.TemporaryDirectory() as td:
        base = Path(td)
        engine = PhialEngine(state_path=base / "state.json", base_dir=base)
        check("engine loads", isinstance(engine, PhialEngine))
        check("default weights", abs(engine.weights["deploy_threshold"] - 0.70) < 1e-9)

        sync = engine.sync_vfs()
        check("sync_vfs structured", sync["status"] == "SYNCED", f"({len(sync['files'])} files)")

        cycle = engine.run_cycle("forage os and check the nexus scaffold")
        check("MGV cycle completes", cycle["status"] == "CYCLE_COMPLETE", f"(verdict={cycle['verdict']}, ratio={cycle['pass_ratio']})")
        check("cycle structured", all(k in cycle for k in ("passed", "failed", "weights_after", "blacklist")))

        state = engine.state()
        check("state persisted", engine.state_path.exists(), f"({engine.state_path.name})")
        check("memory bank fed", state["memory_records"] >= 1)

        first = engine.forge_scaffold()
        second = engine.forge_scaffold()
        check("forge idempotent", first["status"] == "SCAFFOLDED" and second["status"] == "OK" and not second["created"])

        deploy = engine.deploy_artifact("verified research artifact")
        check("deploy writes artifact", deploy["status"] == "DEPLOYED" and Path(deploy["artifact"]).exists())

    print("\nHermes_Prime PhialEngine self-test:", "ALL PASS" if ok else "FAILURES PRESENT")
    return 0 if ok else 1


